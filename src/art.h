/* art.h - art sheets (both zooms) and fonts in VRAM, sprite lookup by NAME, anchored drawing.
   WINDOWS SIDE (uses gfx). Owner: T05. Contract with the generators T02 (world art) and T03 (UI art).
   DESIGN 9, 11.2; STYLE.md 3-4.

   =====================================================================================================
   GENERATED HEADER CONVENTION (T02, T03 must emit exactly this; art.cpp is the only includer)
   =====================================================================================================
   Each generator writes ONE index header into art/ (the Makefile has /Iart):
     art/art_world.h   (T02 gen_art.py)  defines  static const ArtSheet art_world_sheets[];
                                                   #define ART_WORLD_SHEET_COUNT <n>
     art/art_ui.h      (T03 gen_ui.py)   defines  static const ArtSheet art_ui_sheets[];
                                                   #define ART_UI_SHEET_COUNT <n>
                                                   static const ArtFont *const art_ui_fonts[];
                                                   #define ART_UI_FONT_COUNT <n>
   The index may #include per-sheet headers (art/sheet_<name>.h) or hold the tables itself. Generated
   headers hold only static const data of the types below (no typedefs), have include guards, are ASCII,
   and start with "generated by ... - do not edit". Example:
       static const ArtSpr sheet_world0_64[] = {
           { "grass0", 0, 0, 64, 32, 32, 32, -1, -1 },
           { "house_t2_v0_r0", 128, 0, 64, 70, 32, 70, 40, 6 }, ... };
       static const ArtSheet art_world_sheets[] = {
           { "art\\world0_64.bmp", ZOOM_64, 1, sheet_world0_64, 123 }, ... };
   BMPs: 24-bit BI_RGB, width <= ATLAS_MAX_W (640), any height, key RGB(255,0,255), colours pre-rounded
   to RGB565. Paths are relative to the exe dir. art_init() loads every sheet listed; T05 adds the two
   #includes to art.cpp once the generators have produced them (until then art_init() has no sprites
   and every lookup returns ART_MISSING).

   Uniqueness: sprite names are unique within a zoom. World sprites must exist with the SAME name in both
   zooms (art_init warns about names missing in one zoom). UI sheets use zoom ART_ZOOM_ANY.

   =====================================================================================================
   NAMING (the stable contract between generators and code; ids are resolved at init, never hard-coded)
   =====================================================================================================
   Masks MM are two decimal digits 00..15 of neighbour bits NE=1, SE=2, SW=4, NW=8 (common.h DIR_*).
   Terrain (64x32 / 32x16 tiles, anchor = south vertex):
     grass<V>          V = 0..2 (2 = meadow)        water<F>      F = shimmer frame 0..2 (1,2 optional)
     shore<NN>         NN = 01..14 land corners n=1 e=2 w=4 s=8 (STYLE.md 4)   [optional frames shore<NN>_<F>]
     field_crop, field_plough, marsh, rock (1x1 lot sprite), forest_<mixed|spruce|birch|pine>[<V>]
     tree_<kind>       single decorative trees (overlay, no ground), TF_TREE tiles
   Roads (key = RoadDef.key: grav, road, main, mway, rail):
     <key>_<MM>        autotile piece, e.g. road_05 = straight along Y (NE+SW), road_10 along X, road_00 isolated
     <key>_bridge_<MM> MM = 05 or 10 only
   Power: power_<MM> (pole + wires, overlay), wire_<MM> (wires only, over a road tile).
   Lots (key = BuildingDef.key, R = rotation 0..3, V = variant):
     <key>_v<V>_r<R>         normal                  e.g. house_t2_v3_r1
     <key>_v<V>_ab_r<R>      abandoned               (fallback: normal)
     <key>_build_r<R>        construction stage      (fallback: build_<W>x<H>_r<R>, footprint at rot 0)
     <key>_ground_r<R>       flat lot ground for overlay mode (fallback: ground_<W>x<H>_r<R>)
     Fallbacks for any kind: missing r<R> -> r0 (symmetric art), missing v<V> -> v0.
   Dynamic: car<N>_<px|ny|nx|py> (N = colour 0..15; anchor = car ground centre, STYLE.md 9),
     smoke<F> (puff frames), fire<F> (v1.0).
   Overlay/cursor diamonds (keyed, one tile): ovl_<R>_<L> (R = OVR_* ramp, L = level 0..7, 50% checker
     dither), cur_ok, cur_bad, cur_sel, cur_query, zone_<Z> (Z = ZONE_* 1..4 tint).
   Hotspot (hx, hy): chimney top for BDF_SMOKE buildings (life.cpp spawns smoke there); -1,-1 = none.
   UI sheets: names chosen by T03 (documented in art/UI.md), e.g. icon_<tool>, btn_<state>, frame_*.
*/
#ifndef ART_H
#define ART_H
#include "common.h"
#include "gfx.h"

/* ------------------------------------------------------------------ generated-data types */
#define ART_ZOOM_ANY (-1)
typedef struct {
    const char *name;
    s16 x, y, w, h;      /* rect in the sheet */
    s16 ax, ay;          /* anchor inside the sprite: south vertex of the footprint (tiles, lots, overlays),
                            car ground centre (cars), 0,0 (UI pieces) */
    s16 hx, hy;          /* hotspot inside the sprite (chimney top), -1,-1 = none */
} ArtSpr;
typedef struct {
    const char   *bmp;   /* "art\\world0_64.bmp" relative to the exe dir */
    s8            zoom;  /* ZOOM_64, ZOOM_32 or ART_ZOOM_ANY */
    s8            keyed; /* 1 = RGB(255,0,255) transparent */
    const ArtSpr *spr;
    s16           count;
} ArtSheet;
/* PL4: world art is stored as PIECES on small pages (art/ART.md 9). A world sprite = a logical box (w, h, anchor,
   hotspot: exactly as rendered) plus 0..n pieces, each a rectangle of one page placed at (dx, dy) inside the box
   (transparent margins trimmed per half-tile column; ART.md 8). Generated by gen_art.py into sheet_world_<z>.h; the pages are
   listed in art_world_sheets[] with spr = NULL, count = 0, and art_world_sets[] (ART_WORLD_SET_COUNT) holds one
   ArtPieceSet per zoom. UI sheets keep the one-rect-per-sprite ArtSpr form. */
typedef struct {
    u8  page;            /* index into art_world_sheets */
    s16 x, y, w, h;      /* rect in the page */
    s16 dx, dy;          /* its top-left inside the sprite box */
} ArtPiece;
typedef struct {
    const char *name;
    s16 w, h, ax, ay, hx, hy;  /* logical sprite box, anchor, hotspot (as ArtSpr) */
    s16 first, count;          /* its pieces: pieces[first .. first + count) */
} ArtPSpr;
typedef struct {
    s8              zoom;
    const ArtPiece *pieces;
    s16             npieces;
    const ArtPSpr  *spr;
    s16             count;
} ArtPieceSet;
typedef struct {
    u8  code;            /* byte code (Latin-1; 1..5 = GLYPH_* symbols in text.h) */
    s16 x, y;            /* rect in the font's sheet */
    u8  w, h;
    s8  ox, oy;          /* offset from the pen position (top of the line) to the glyph's top-left */
    u8  adv;             /* pen advance in px */
} ArtGlyph;
typedef struct {
    const char     *name;      /* "body_dark", "body_light", "head" */
    const char     *bmp;       /* sheet holding the glyphs (also listed in the ART_UI sheets) */
    u8              line_h;    /* line height */
    u8              baseline;  /* from the line top */
    const ArtGlyph *glyphs;
    s16             count;
} ArtFont;

/* ------------------------------------------------------------------ runtime */
#define ART_MISSING 0          /* id of the placeholder sprite (magenta diamond) */
typedef struct {
    const Img *img;            /* sheet image in VRAM: the FIRST piece's (UI sprites: their only piece) */
    s16 x, y, w, h, ax, ay, hx, hy;   /* x, y = first piece in its sheet; w, h = the logical sprite box */
    s16 piece0, npieces;       /* PL4: runtime pieces (art.cpp); draw world sprites only via art_draw* /
                                  art_blit_part, never with img/x/y directly (a world sprite may have several) */
} ArtSprite;
enum { ART_LOT_NORMAL, ART_LOT_ABANDONED, ART_LOT_BUILDING, ART_LOT_GROUND };

int  art_init(void);           /* load all sheets of both zooms + fonts; 0 = fatal (missing BMP / VRAM
                                  full; logged with the sheet name and VRAM numbers) */
void art_shutdown(void);
int  art_find(const char *name);         /* id valid for both zooms; ART_MISSING if unknown (logs once) */
int  art_findf(const char *fmt, ...);    /* art_find of a formatted name */
int  art_exists(const char *name);       /* 1/0, no log (enumerating variants, optional frames) */
int  art_lot_sprite(const char *key, int variant, int rot, int kind, int w, int h); /* applies the
                                            naming fallbacks above; w,h = footprint at rot 0 */
const ArtSprite *art_get(int zoom, int id); /* never NULL (ART_MISSING placeholder) */
const char *art_name(int id);
int  art_count(void);                    /* ids are 0 .. art_count()-1 */
int  art_variants(const char *key);      /* number of <key>_v<V>_r0 sprites (consecutive from v0) */

/* Drawing into the current gfx target (origin/clip apply). (x, y) is where the ANCHOR lands. */
void art_draw(int zoom, int id, int x, int y);
void art_draw_cols(int zoom, int id, int x, int y, int col0, int col1); /* only sprite columns
                                            [col0, col1) (32-px strip slicing, STYLE.md 4) */
int  art_opaque(int zoom, int id, int px, int py);  /* sprite pixel not key (tall-building picking) */

/* Fonts (T03 metrics, drawn by ui_text). */
const ArtFont *art_font(const char *name);   /* NULL if missing (logged) */
const Img     *art_font_img(const ArtFont *f);

int  art_vram_kb(void);                  /* VRAM used by all sheets (DESIGN 11.2 budget: <= 9 MB) */
/* ---- T05 additions */
int  art_world_vram_kb(int zoom);        /* size of that zoom's world sheets (resident or not) */
/* Zoom residency: keep only one zoom's world sheets in VRAM (UI sheets always stay). -1 = both (default
   after art_init). WHICH ART IS RESIDENT WHEN: both zooms, always, unless render_init finds the free VRAM
   too short for both zooms + its chunk pool (in practice 1024x768 on the 14 MB Voodoo3; 640 and 800 keep
   both). Then only the CURRENT zoom's world sheets are in VRAM (render_set_zoom swaps them, ~0.3 s) and
   art_resident_zoom() says which. A world sprite asked for at the other zoom comes back as the resident
   zoom's copy (art_get falls back, so it has the other size: 64x32 instead of 32x16 diamonds); UI code
   that needs a fixed size (legend swatches) should check art_resident_zoom() or use UI-sheet art. The
   evicted zoom's pixels stay in the heap (art_pixels/art_opaque keep working). 0 = VRAM full. */
int  art_set_resident_zoom(int zoom);
int  art_resident_zoom(void);
int  art_max_up(int zoom);               /* largest anchor-y of any world sprite (reach above its anchor) */
int  art_max_half_w(int zoom);           /* largest horizontal reach of a world sprite from its anchor */
const PIX *art_pixels(int zoom, int id, int *pitch); /* system-memory pixels of the top-left of the sprite art_get returns
                                            (ghost images, minimap colours, picking); NULL if none. PL4: a
                                            multi-piece sprite is assembled into a scratch buffer that the next
                                            art_pixels call overwrites (pitch = its w) */
int  art_selftest(void);                 /* -test art: every name the code needs (defs keys x variants x
                                            rotations x kinds, road masks, terrain, overlays) is listed
                                            in the log if missing; returns the number missing */
/* F3 addition: 0 = that zoom's world art could not be made resident at this resolution (art_init found no VRAM
   room for it, e.g. the 64 zoom at 1024x768 on a 16 MB Voodoo3): the game stays at the other zoom */
int  art_zoom_available(int zoom);
/* PL4 addition: blit the sprite-local rectangle (sx, sy, w, h) of sprite id with its top-left at (dx, dy) of the
   current target (origin/clip apply): one blit per piece that overlaps it (render.cpp strips + occlusion fix) */
void art_blit_part(int zoom, int id, int sx, int sy, int w, int h, int dx, int dy);
/* 1.1 W2 seasons: winter art = the same pages and piece table with other pixels (art/art_world.h art_world_winter[]).
   art_set_season(1/0) swaps every world page's pixels (both zooms) and re-uploads the resident ones into their
   existing surfaces (0 KB extra VRAM); returns 1 when the art changed (the caller flushes its caches: chunks, ghost
   copies, minimap colours). No-op (0) with INI winter_art=0 or missing winter pages (art_winter_available() = 0). */
int  art_set_season(int winter);
int  art_season(void);                   /* 1 = winter art shown */
int  art_winter_available(void);

#endif
