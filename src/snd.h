/* snd.h - sound effects and ambient town loops. WINDOWS SIDE (header has no windows.h). Owner: T07.
   DESIGN 10. DirectSound (DX5-level API, dsound.dll loaded at run time with LoadLibrary, so a PC without a
   sound device or DirectSound simply runs silently). One static buffer per sample, created at init; a pool
   of duplicated voices for effects; one looping buffer per ambient layer. PlaySound is banned (blocks 5-9 ms).
   All functions are safe no-ops when sound is off or snd_init failed/was never called.

   Files: sfx\<name>.wav next to the exe (22050 Hz 16-bit mono, generated by tools/make_sfx.py, see sfx/SFX.md).
   A missing file only silences that sound.

   Volumes: final = sample base (snd.cpp table) * vol100/100 * master (g_cfg.volume) * group volume.
   Group volumes come from LAHIO.INI [Lahio] sfx_volume=0..100 (default 100) and
   ambient_volume=0..100 (default 70), read by snd_init (config.cpp does not know them yet) and settable
   with snd_set_group_volume (settings menu, T10).
   Cost (measured in the 86Box VM, SB AWE64 hardware buffers): snd_play ~0.17 ms (Stop/SetPosition/
   SetVolume/SetPan/Play), 0.25-1 ms when a voice must duplicate a new sample's buffer - so play a few sounds
   per frame, not dozens. snd_tick ~10 us idle; at most 3 SetVolume calls while ambient layers glide. */
#ifndef SND_H
#define SND_H
#include "common.h"

/* Effect ids (order = file table in snd.cpp = SOUNDS in tools/make_sfx.py). Not saved: may be extended. */
enum { SND_CLICK,        /* UI click (buttons, list items) */
       SND_KEY,          /* bakelite tool key clunk (tool select) */
       SND_PANEL_OPEN,   /* panel / fly-out opens */
       SND_PANEL_CLOSE,  /* panel closes */
       SND_BUILD,        /* construction thud (tool commit, building placed, lot built) */
       SND_ROAD,         /* road laying (gravel crunch) */
       SND_BULLDOZE,     /* bulldozer / demolish */
       SND_CASH,         /* cash register (month-end tax) */
       SND_CHIME,        /* ticker chime (ordinary news) */
       SND_WARN,         /* warning bell (urgent ticker item, problem) */
       SND_TYPE,         /* typewriter burst (letters, decrees) */
       SND_STAMP,        /* rubber stamp (decree approved/rejected) */
       SND_FIREBELL,     /* fire */
       SND_PAPER,        /* newspaper rustle (newspaper opens) */
       SND_FANFARE,      /* milestone fanfare (town status, population milestones) */
       SND_DENY,         /* error buzz: invalid action / no money */
       SND_COUNT };

/* Ambient loop layers (crossfaded, looping). */
enum { AMB_BIRDS,        /* wind in trees + songbirds: small town, parks, forest on screen */
       AMB_TRAFFIC,      /* distant traffic hum: grows with population / road traffic */
       AMB_INDUSTRY,     /* sawmill / works whine: industry nearby */
       AMB_COUNT };

enum { SND_GROUP_SFX, SND_GROUP_AMBIENT, SND_GROUP_COUNT };

int  snd_init(void *hwnd);             /* HWND; 0 = no sound (game continues) */
void snd_shutdown(void);
void snd_play(int id, int vol100);     /* non-positional; vol100 = 0..100 extra factor */
/* Positional: pan/attenuate by the tile's position relative to the camera centre (game passes it).
   pan100 -100 (left) .. +100 (right); dist_tiles from the camera centre: full volume within 8 tiles,
   fading linearly to silence at 48 (nothing is played beyond). */
void snd_play_at(int id, int vol100, int pan100 /* -100 left .. +100 right */, int dist_tiles);
void snd_set_volume(int vol100);       /* master, from config */
/* Ambient loop layers 0..100 each (birds, traffic, industry); updated a few times per second by game.cpp
   from sim stats and what is on screen. Same as snd_ambient for each layer. */
void snd_set_ambient(int birds, int traffic, int industry);
void snd_tick(void);                   /* once per frame: mixing housekeeping */
int  snd_selftest(void);               /* -test snd: plays every effect, logs; 0 pass, >0 failures */

/* ---- T07 additions ---------------------------------------------------------------------------------- */
/* One ambient layer (AMB_*), target 0..100. The audible volume glides to the target (about 1.5 s for the
   full range, driven by snd_tick), so callers may set raw values at any rate. A layer at 0 is stopped
   (no mixing cost); it restarts from where it was in the loop. */
void snd_ambient(int layer, int vol100);
/* Effect panned from a screen x coordinate (0 = left edge, screen_w = right edge). Gentle pan (+-60%),
   for UI events tied to a map position on screen (building placed, fire). */
void snd_play_sx(int id, int vol100, int screen_x, int screen_w);
void snd_set_group_volume(int group, int vol100); /* SND_GROUP_*: 0..100 */
int  snd_group_volume(int group);
int  snd_active(void);                 /* 1 if DirectSound is running */
void snd_stop_all(void);               /* silence effects and ambience at once (pause menu, loading) */
const char *snd_name(int id);          /* file stem of an effect ("click"), "?" if out of range */

#endif
