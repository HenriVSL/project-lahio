#!/usr/bin/env python3
"""gen_bench20k.py - T13: writes scripts/bench20k.txt, a dense ~20k town on the Lakeland seed-7 map (the
town1 map) for the performance bench. Street grid every 7 tiles, blocks of 6x6: apartments/houses/
commercial in the west, industry east of the national road, a service block every few blocks, coal
plants + wells for utilities. Tools reject what doesn't fit (water, rock); the bench only needs density.
tests/test_perf.cpp (KAUP_BENCHCITY=1) runs it headless for 12 years and saves BENCH20K.KAU."""
import os
X0, X1, Y0, Y1, S = 2, 107, 4, 102, 7
out = ["# bench20k.txt - generated by tools/gen_bench20k.py (T13). Lakeland seed 7. Headless only.",
       "townhall"]
xs = list(range(X0, X1 + 1, S)); ys = list(range(Y0, Y1 + 1, S))
for y in ys: out.append(f"road {X0} {y} {X1} {y} street straight")
for x in xs: out.append(f"road {x} {Y0} {x} {Y1} street straight")
for y in ys: out.append(f"power {X0} {y} {X1} {y}")
# industry east of the national road (x 109..126, y 71..101)
IX = list(range(109, 127, 6)); IY = list(range(71, 102, 6))
for y in IY: out.append(f"road 108 {y} 126 {y} street straight")
for x in IX: out.append(f"road {x} 71 {x} 101 street straight")
for y in IY: out.append(f"power 108 {y} 126 {y}")
blocks = []
for j, y in enumerate(ys[:-1]):
    for i, x in enumerate(xs[:-1]):
        blocks.append((i, j, x + 1, y + 1))
builds, zones, zones2 = [], [], []
for (i, j, bx, by) in blocks:
    k = (i * 7 + j * 3) % 9
    if k == 0:      # service block
        builds += [f"build school {bx} {by}", f"build sauna {bx+3} {by}", f"build clinic {bx+5} {by}",
                   f"build fire_station {bx} {by+3}", f"build sauna {bx+3} {by+3}", f"build well {bx+5} {by+5}",
                   f"build well {bx} {by+5}", f"build well {bx+5} {by+3}"]
        zones.append(f"zone {bx} {by} {bx+5} {by+5} houses")
    elif k == 4 and j % 2 == 0:   # utility block
        builds += [f"build coal_plant {bx} {by}", f"build well {bx+3} {by}", f"build well {bx+5} {by}",
                   f"build well {bx+3} {by+2}", f"build well {bx+5} {by+2}", f"build sauna {bx} {by+5}",
                   f"build well {bx+2} {by+5}"]
        zones.append(f"zone {bx} {by} {bx+5} {by+5} commercial")
    else:
        z = "industry" if (i >= 11 and j >= 8 and (i + j) % 3 != 0) else "commercial" if (j % 4 == 1 and i % 2 == 0) else ("houses" if (i + j) % 5 == 0 else "apartments")
        (zones2 if z == "apartments" else zones).append(f"zone {bx} {by} {bx+5} {by+5} {z}")
for x in IX[:-1]:
    for y in IY[:-1]:
        if x == IX[0]:      # power district: two coal plants per block
            builds += [f"build coal_plant {x+1} {y+1}", f"build coal_plant {x+3} {y+3}"]
        else:
            zones.append(f"zone {x+1} {y+1} {x+5} {y+5} industry")
out += builds + zones
# apartments unlock with the Market town status: zone them after the houses have grown
out += ["speed 3", "wait 36", "dump report"] + zones2 + ["wait 108", "dump report"]
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts", "bench20k.txt")
open(p, "w", newline="\r\n").write("\n".join(out) + "\n")
print(p, len(out), "lines")
